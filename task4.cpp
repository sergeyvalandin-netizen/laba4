#include <iostream>
#include <iomanip>

using namespace std;

int main() {
    int r, c;
    cout << "Введите количество строк r (2..8) и столбцов c (2..8): ";
    cin >> r >> c;

    int count_ge_150 = 0;

    cout << "\nТаблица цен:\n";

    // Используем индексы с 1, как это обычно подразумевается в математических формулах
    for (int i = 1; i <= r; ++i) {
        for (int j = 1; j <= c; ++j) {
            int price = 100 + 20 * i - 5 * j;

            // Если результат меньше 50, выводим 50
            if (price < 50) {
                price = 50;
            }

            // Выводим ячейку с выравниванием для красоты таблицы
            cout << setw(5) << price;

            // Считаем ячейки с ценой >= 150
            if (price >= 150) {
                count_ge_150++;
            }
        }
        cout << endl; // Перенос строки после каждой строки таблицы
    }

    cout << "\nКоличество ячеек с итоговой ценой не ниже 150: " << count_ge_150 << endl;

    return 0;
}